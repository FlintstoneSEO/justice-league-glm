import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const embedsDirectory = path.join(root, 'wix-embeds');
const outputPath = path.join(embedsDirectory, 'business-growth-grant-custom-element.js');
const applicationUrl = 'https://forms.gle/LzuDSyiCvp7w8qpN9';
const sources = [
  ['home', 'Home.html'],
  ['about', 'About.html'],
  ['grantor', 'Lead Grantor.html'],
  ['eligibility', 'Eligibility.html'],
  ['apply', 'How to Apply.html'],
  ['timeline', 'Timeline.html'],
  ['faq', 'FAQ.html'],
  ['closing', 'Closing.html'],
];

function extract(source, pattern, label, fileName) {
  const match = source.match(pattern);
  if (!match?.[1]) throw new Error(`Unable to extract ${label} from ${fileName}`);
  return match[1].trim();
}

function normalizeCss(css) {
  return css
    .replace(/:root\s*\{/g, ':host {')
    .replace(/url\(["']PASTE_WIX_HERO_IMAGE_URL_HERE["']\)/g, 'var(--hero-image, none)')
    .replace(/html\s*,\s*body\s*\{[^}]*\}/g, '')
    .replace(/body\s*\{[^}]*\}/g, '')
    .trim();
}

function normalizeMarkup(markup) {
  return markup
    .replace(/<script\b[\s\S]*?<\/script>/gi, '')
    .replace(/<!--([\s\S]*?)-->/g, '')
    .replaceAll('https://forms.gle/LzuDSyiCvp7w8qpN9', applicationUrl)
    .replace(/target=["']_top["']/gi, 'target="_blank" rel="noopener noreferrer"')
    .replace(/<svg(?![^>]*\baria-hidden=)/g, '<svg aria-hidden="true" focusable="false"')
    .trim();
}

const sections = sources.map(([key, fileName]) => {
  const source = fs.readFileSync(path.join(embedsDirectory, fileName), 'utf8');
  return {
    key,
    css: normalizeCss(extract(source, /<style[^>]*>([\s\S]*?)<\/style>/i, 'styles', fileName)),
    markup: normalizeMarkup(extract(source, /<body[^>]*>([\s\S]*?)<\/body>/i, 'body', fileName)),
  };
});

const generated = `/* Generated by scripts/build-business-growth-grant-custom-element.mjs. */
const SECTION_DEFINITIONS = ${JSON.stringify(sections, null, 2)};

class BusinessGrowthGrant extends HTMLElement {
  static get observedAttributes() {
    return ['hero-image-url'];
  }

  connectedCallback() {
    if (!this.shadowRoot) this.attachShadow({ mode: 'open' });
    this.render();
  }

  attributeChangedCallback() {
    if (this.shadowRoot) this.applyHeroImage();
  }

  render() {
    this.shadowRoot.innerHTML = '<style>:host{display:block;background:#050505}.section-host{display:block}</style><main></main>';
    const main = this.shadowRoot.querySelector('main');

    for (const section of SECTION_DEFINITIONS) {
      const host = document.createElement('div');
      host.className = 'section-host';
      host.dataset.section = section.key;
      host.attachShadow({ mode: 'open' });
      host.shadowRoot.innerHTML = \`<style>:host{display:block;font-family:Arial,Helvetica,sans-serif}a:focus-visible,button:focus-visible{outline:3px solid #f4b400;outline-offset:4px}@media(prefers-reduced-motion:reduce){*,*::before,*::after{animation:none!important;scroll-behavior:auto!important;transition:none!important}}\${section.css}</style>\${section.markup}\`;
      main.append(host);
      this.bindSectionEvents(host);
    }

    this.applyHeroImage();
  }

  bindSectionEvents(host) {
    host.shadowRoot.querySelectorAll('a[href^="#"]').forEach((link) => {
      link.addEventListener('click', (event) => {
        event.preventDefault();
        this.scrollToSection(link.getAttribute('href').slice(1));
      });
    });

    host.shadowRoot.querySelectorAll('.faq-question').forEach((button) => {
      button.addEventListener('click', () => {
        const item = button.closest('.faq-item');
        const expanded = button.getAttribute('aria-expanded') === 'true';
        item.classList.toggle('active', !expanded);
        button.setAttribute('aria-expanded', String(!expanded));
      });
    });
  }

  scrollToSection(id) {
    const host = [...this.shadowRoot.querySelectorAll('.section-host')].find((candidate) =>
      candidate.dataset.section === id || candidate.shadowRoot.getElementById(id)
    );
    if (!host) return;
    const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    host.scrollIntoView({ behavior: reduceMotion ? 'auto' : 'smooth', block: 'start' });
  }

  applyHeroImage() {
    const home = this.shadowRoot?.querySelector('[data-section="home"]');
    if (!home) return;
    const value = this.getAttribute('hero-image-url');
    if (!value) {
      home.style.removeProperty('--hero-image');
      return;
    }
    try {
      const url = new URL(value);
      if (!['http:', 'https:'].includes(url.protocol)) return;
      const safeUrl = url.href;
      home.style.setProperty('--hero-image', \`url("\${safeUrl}")\`);
    } catch (error) {
      console.error('Invalid Business Growth Grant hero image URL.', error);
    }
  }
}

if (!customElements.get('jl-business-growth-grant')) {
  customElements.define('jl-business-growth-grant', BusinessGrowthGrant);
}
`;

fs.writeFileSync(outputPath, generated, 'utf8');
console.log(`Generated ${path.relative(root, outputPath)} from ${sections.length} section files.`);
